def main():
    """Main entry point - processes all laws in LAWS_TO_EXTRACT"""
    global _extraction_in_progress, _all_completed_extractions

    # Register interrupt handler for graceful shutdown
    signal.signal(signal.SIGINT, handle_interrupt)

    # Create output directory if it doesn't exist
    Path(OUTPUT_DIR).mkdir(exist_ok=True)
    print(f"Output directory: {OUTPUT_DIR}/")

    print("\n" + "="*60)
    print("GRAPH RAG EXTRACTION FOR MALTA LAWS")
    print("="*60)
    print(f"\nLaws to extract: {len(LAWS_TO_EXTRACT)}")
    for i, law in enumerate(LAWS_TO_EXTRACT, 1):
        print(f"  {i}. {law['name']} ({law['cap']})")

    all_extractions = []

    for i, law_config in enumerate(LAWS_TO_EXTRACT, 1):
        print("\n" + "="*60)
        print(f"EXTRACTING LAW {i}/{len(LAWS_TO_EXTRACT)}: {law_config['name']}")
        print("="*60)

        # Check if this law was already extracted (resume capability)
        code_clean = normalize_code(law_config["cap"])
        output_file = Path(OUTPUT_DIR) / f"extraction_{code_clean}.json"
        if output_file.exists():
            print(f"[SKIP] Already extracted - file exists: {output_file}")
            continue

        # Process this law
        extraction = process_law(
            pdf_path=law_config["pdf_path"],
            cap=law_config["cap"],
            law_name=law_config["name"],
            page_range=law_config.get("page_range")
        )

        # Track in-progress extraction (for interrupt handler)
        _extraction_in_progress = extraction

        # Print summary for this law
        print("\n" + "-"*40)
        print(f"SUMMARY: {extraction.law_name} ({extraction.law_code})")
        print("-"*40)
        print(f"Type: {extraction.law_type}")
        print(f"Metrics:")
        for key, value in extraction.metrics.items():
            print(f"  {key}: {value}")

        # Save this extraction to its own JSON file in the output directory
        save_extraction(extraction, OUTPUT_DIR)
        all_extractions.append(extraction)

        # Track completed extractions (for interrupt handler)
        _all_completed_extractions.append(extraction)
        _extraction_in_progress = None  # Clear in-progress tracker

    # Final summary
    print("\n" + "="*60)
    print("ALL EXTRACTIONS COMPLETE")
    print("="*60)
    print(f"Total laws extracted: {len(all_extractions)}")
    for ext in all_extractions:
        items_count = ext.metrics.get(f"{ext.content_key}_extracted", 0)
        print(f"  - {ext.law_code}: {items_count} {ext.content_key}, {ext.metrics.get('edges_created', 0)} edges")

    print("\nDone!")


if __name__ == "__main__":
    main()
