def extract_fallback_text(
    model: GenerativeModel,
    page: fitz.Page,
    page_num: int,
    cap: str,
    law_name: str
) -> Optional[Dict]:
    """Fallback extraction - just get raw text from the page when structured extraction fails.

    Returns a miscellaneous chunk with the raw page text.
    """
    prompt = f"""You are extracting text from page {page_num + 1} of {law_name} ({cap}).

The structured extraction failed, so just extract ALL visible text from this page.

Return a simple JSON:
{{
    "page_text": "All the text visible on this page, preserving structure as much as possible...",
    "has_content": true
}}

If the page is blank or has no meaningful text, return:
{{
    "page_text": "",
    "has_content": false
}}

Return ONLY valid JSON."""

    img_base64 = page_to_image_base64(page)
    image_part = Part.from_data(base64.b64decode(img_base64), mime_type="image/png")

    try:
        response = generate_content_with_timeout(
            model,
            [prompt, image_part],
            safety_settings=SAFETY_SETTINGS,
            generation_config={"temperature": 0}
        )

        if response.candidates and response.candidates[0].content:
            raw_text = response.candidates[0].content.parts[0].text.strip()

            # Clean up response
            if raw_text.startswith("```"):
                raw_text = re.sub(r'^```json?\n?', '', raw_text)
                raw_text = re.sub(r'\n?```$', '', raw_text)

            parsed = json.loads(raw_text)

            if parsed.get("has_content") and parsed.get("page_text"):
                return {
                    "id": f"misc:{normalize_code(cap)}/page/{page_num + 1}",
                    "type": "miscellaneous",
                    "text": parsed["page_text"],
                    "page": page_num + 1,
                    "extraction_method": "fallback_ocr"
                }

    except FunctionTimedOut:
        print(f"  Fallback extraction timed out after {API_TIMEOUT}s")
    except Exception as e:
        print(f"  Fallback extraction also failed: {e}")

    return None


