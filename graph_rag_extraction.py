def is_subsidiary_legislation(cap: str) -> bool:
    """Check if this is subsidiary legislation (S.L.) vs main chapter (Cap.)"""
    return cap.strip().upper().startswith("S.L.")


def get_content_type_name(cap: str) -> str:
    """Get the name for content items (articles vs regulations)"""
    return "regulations" if is_subsidiary_legislation(cap) else "articles"


def get_item_type(cap: str) -> str:
    """Get the type for individual items"""
    return "regulation" if is_subsidiary_legislation(cap) else "article"


def get_id_prefix(cap: str) -> str:
    """Get ID prefix based on law type"""
    return "reg" if is_subsidiary_legislation(cap) else "art"


def normalize_code(cap: str) -> str:
    """Normalize law code for ID generation (remove spaces)"""
    return cap.replace(" ", "")


def generate_item_id(cap: str, number: str) -> str:
    """Generate unique ID for article/regulation

    Examples:
        art:Cap.9/5
        reg:S.L.146.02/5
    """
    prefix = get_id_prefix(cap)
    code = normalize_code(cap)
    # Clean the number (remove any leading zeros, spaces)
    clean_num = number.strip()
    return f"{prefix}:{code}/{clean_num}"


def generate_schedule_id(cap: str, schedule_name: Optional[str] = None, regulation_num: Optional[str] = None) -> str:
    """Generate unique ID for schedule or schedule regulation

    Examples:
        sched:S.L.199.01/Schedule
        sched:S.L.199.01/FirstSchedule
        sched:S.L.455.13/Schedule/Reg1
    """
    code = normalize_code(cap)

    # Handle None or empty schedule name
    if not schedule_name:
        clean_name = "Schedule"
    else:
        # Clean schedule name
        clean_name = schedule_name.replace(" ", "").replace("SCHEDULE", "Schedule")
        if not clean_name or clean_name.lower() == "schedule":
            clean_name = "Schedule"

    if regulation_num:
        return f"sched:{code}/{clean_name}/Reg{regulation_num}"
    return f"sched:{code}/{clean_name}"


def extract_main_number(number: str) -> str:
    """Extract main article/regulation number from full number

    Examples:
        "5" -> "5"
        "5(1)" -> "5"
        "5(2)(a)" -> "5"
        "23A" -> "23A"
        "23A(1)" -> "23A"
        "article 492" -> "492"
        "articles 204A" -> "204A"
    """
    # First, strip common prefixes
    cleaned = clean_reference_target(number)
    # Match the main number (digits optionally followed by letter)
    match = re.match(r'^(\d+[A-Za-z]?)', cleaned.strip())
    if match:
        return match.group(1)
    return cleaned.strip()


def clean_reference_target(target: str) -> str:
    """Clean reference target by removing 'article', 'articles', 'regulation', etc.

    Examples:
        "article 492" -> "492"
        "articles 204A" -> "204A"
        "regulation 5" -> "5"
        "5(1)" -> "5(1)"
    """
    if not target:
        return target
    # Remove common prefixes (case-insensitive)
    cleaned = re.sub(r'^(articles?|regulations?|sub-?articles?|sub-?regulations?)\s*', '', target.strip(), flags=re.IGNORECASE)
    return cleaned.strip()


def expand_reference_range(range_str: str) -> List[str]:
    """Expand a range reference like '311 to 318' into individual numbers.

    Examples:
        "311 to 318" -> ["311", "312", "313", "314", "315", "316", "317", "318"]
        "5 to 7" -> ["5", "6", "7"]
        "204A to 204C" -> ["204A", "204B", "204C"]  (letter ranges)
        "5" -> ["5"]  (no range, returns single item)
    """
    range_str = clean_reference_target(range_str)

    # Check for range pattern: "X to Y" or "X-Y"
    range_match = re.match(r'^(\d+[A-Za-z]?)\s*(?:to|-)\s*(\d+[A-Za-z]?)$', range_str.strip(), re.IGNORECASE)

    if not range_match:
        # No range, return single item
        return [range_str.strip()] if range_str.strip() else []

    start_str, end_str = range_match.groups()

    # Check if both are pure numbers
    start_num_match = re.match(r'^(\d+)([A-Za-z]?)$', start_str)
    end_num_match = re.match(r'^(\d+)([A-Za-z]?)$', end_str)

    if not start_num_match or not end_num_match:
        return [start_str, end_str]

    start_num, start_letter = int(start_num_match.group(1)), start_num_match.group(2)
    end_num, end_letter = int(end_num_match.group(1)), end_num_match.group(2)

    result = []

    # If both have same letter suffix or no letter
    if start_letter == end_letter:
        for n in range(start_num, end_num + 1):
            result.append(f"{n}{start_letter}")
    # If letters differ but numbers same (e.g., 204A to 204C)
    elif start_num == end_num and start_letter and end_letter:
        for letter in range(ord(start_letter.upper()), ord(end_letter.upper()) + 1):
            result.append(f"{start_num}{chr(letter)}")
    # Otherwise, just do numeric range (ignore letters)
    else:
        for n in range(start_num, end_num + 1):
            result.append(str(n))

    return result if result else [range_str]


def parse_external_reference(ref_text: str, target_law: str) -> Dict:
    """Parse an external reference and determine the appropriate ID structure.

    Returns:
        Dict with 'target_id' and 'has_article'

    Examples:
        ("article 7", "Cap. 16") -> {"target_id": "art:Cap.16/7", "has_article": True}
        ("Immigration Act", None) -> {"target_id": "law:ImmigrationAct", "has_article": False}
        ("", "Cap. 16") -> {"target_id": "law:Cap.16", "has_article": False}
    """
    if not target_law:
        return {"target_id": None, "has_article": False}

    target_code = normalize_code(target_law)
    cleaned_ref = clean_reference_target(ref_text) if ref_text else ""

    # Check if we have a specific article/regulation number
    num_match = re.match(r'^(\d+[A-Za-z]?)(?:\(|$)', cleaned_ref)

    if num_match:
        # We have a specific article number
        article_num = num_match.group(1)
        prefix = "reg" if is_subsidiary_legislation(target_law) else "art"
        return {
            "target_id": f"{prefix}:{target_code}/{article_num}",
            "has_article": True
        }
    else:
        # Just the law reference, no specific article
        return {
            "target_id": f"law:{target_code}",
            "has_article": False
        }


def page_to_image_base64(page: fitz.Page, dpi: int = 150) -> str:
    """Convert PDF page to base64 encoded PNG"""
    mat = fitz.Matrix(dpi / 72, dpi / 72)
    pix = page.get_pixmap(matrix=mat)
    img_bytes = pix.tobytes("png")
    return base64.b64encode(img_bytes).decode('utf-8')


