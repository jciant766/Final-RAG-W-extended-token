def generate_law_metadata(
    model: GenerativeModel,
    law_name: str,
    cap: str,
    sample_items: List[Dict],
    parent_summary: Optional[str] = None
) -> Optional[LawMetadata]:
    """Generate metadata for a law using AI.

    Args:
        model: The Gemini model to use
        law_name: Name of the law
        cap: Law code (Cap. X or S.L. X.XX)
        sample_items: Sample of extracted articles/regulations for context
        parent_summary: Summary of parent law (for S.L. laws)

    Returns:
        LawMetadata object or None on failure
    """
    is_subsidiary = is_subsidiary_legislation(cap)

    # Build sample text from first few items
    sample_texts = []
    for item in sample_items[:5]:
        if item.get("text"):
            sample_texts.append(f"{item.get('number', 'N/A')}: {item['text'][:500]}")

    sample_text = "\n\n".join(sample_texts) if sample_texts else f"Law: {law_name}"

    prompt = build_metadata_prompt(law_name, cap, sample_text, is_subsidiary, parent_summary)

    try:
        response = generate_content_with_timeout(
            model,
            prompt,
            safety_settings=SAFETY_SETTINGS,
            generation_config={"temperature": 0.3}
        )

        if response.candidates and response.candidates[0].content:
            raw_text = response.candidates[0].content.parts[0].text.strip()

            # Clean up response
            if raw_text.startswith("```"):
                raw_text = re.sub(r'^```json?\n?', '', raw_text)
                raw_text = re.sub(r'\n?```$', '', raw_text)

            parsed = json.loads(raw_text)

            return LawMetadata(
                purpose=parsed.get("purpose", ""),
                key_topics=parsed.get("key_topics", []),
                scope=parsed.get("scope", ""),
                categories=parsed.get("categories", ["other"]),
                summary_text=parsed.get("summary_text", ""),
                relation_to_parent=parsed.get("relation_to_parent") if is_subsidiary else None,
                status="success"
            )

    except FunctionTimedOut:
        print(f"  Warning: Metadata generation timed out after {API_TIMEOUT}s")
    except Exception as e:
        print(f"  Warning: Could not generate metadata: {e}")

    return None


