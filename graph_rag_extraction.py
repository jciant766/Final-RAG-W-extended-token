def extract_page(
    model: GenerativeModel,
    page: fitz.Page,
    page_num: int,
    cap: str,
    law_name: str,
    prev_item_number: Optional[str] = None,
    prev_item_ended: bool = True,
    prev_schedule_section: Optional[str] = None,
    prev_schedule_ended: bool = True,
    prev_form_number: Optional[str] = None,
    prev_form_ended: bool = True
) -> Tuple[Optional[Dict], str]:
    """Extract content from a single page

    Returns:
        Tuple of (parsed_response, raw_response)
        Returns (None, error_message) on failure
    """
    is_subsidiary = is_subsidiary_legislation(cap)

    # Build prompt
    prompt = build_extraction_prompt(
        cap=cap,
        law_name=law_name,
        is_subsidiary=is_subsidiary,
        prev_item_number=prev_item_number,
        prev_item_ended=prev_item_ended,
        prev_schedule_section=prev_schedule_section,
        prev_schedule_ended=prev_schedule_ended,
        prev_form_number=prev_form_number,
        prev_form_ended=prev_form_ended
    )

    # Convert page to image
    img_base64 = page_to_image_base64(page)
    image_part = Part.from_data(base64.b64decode(img_base64), mime_type="image/png")

    # Call model
    try:
        response = generate_content_with_timeout(
            model,
            [prompt, image_part],
            safety_settings=SAFETY_SETTINGS,
            generation_config={"temperature": 0}
        )

        # Check for blocked response
        if not response.candidates:
            return None, "NO_CANDIDATES"

        candidate = response.candidates[0]
        if candidate.finish_reason.name == "SAFETY":
            return None, "SAFETY_BLOCKED"

        if not candidate.content or not candidate.content.parts:
            return None, "EMPTY_RESPONSE"

        raw_text = candidate.content.parts[0].text.strip()

        # Parse JSON
        # Clean up response (remove markdown if present)
        if raw_text.startswith("```"):
            raw_text = re.sub(r'^```json?\n?', '', raw_text)
            raw_text = re.sub(r'\n?```$', '', raw_text)

        parsed = json.loads(raw_text)
        return parsed, raw_text

    except FunctionTimedOut as e:
        print(f"\n  Timeout after {API_TIMEOUT}s")
        return None, "TIMEOUT"
    except json.JSONDecodeError as e:
        # Print the raw text that failed to parse for debugging
        print(f"\n  JSON Parse Error: {str(e)[:100]}")
        return None, f"JSON_PARSE_ERROR: {str(e)[:50]}"
    except Exception as e:
        error_msg = str(e)
        # Catch any timeout-related errors (including func_timeout threading issues)
        if "timeout" in error_msg.lower() or "timed out" in error_msg.lower() or "deadline" in error_msg.lower():
            print(f"\n  Timeout detected in exception")
            return None, "TIMEOUT"
        print(f"\n  Exception: {error_msg[:100]}")
        return None, f"ERROR: {error_msg[:50]}"


def extract_with_fallback(
    models: Dict[str, GenerativeModel],
    page: fitz.Page,
    page_num: int,
    cap: str,
    law_name: str,
    **kwargs
) -> Tuple[Optional[Dict], str, str]:
    """Try extraction with fallback models

    Returns:
        Tuple of (parsed_response, raw_response, model_used)
    """
    model_order = ["primary", "fallback_1", "fallback_2"]

    for model_key in model_order:
        if model_key not in models:
            continue

        model = models[model_key]

        for attempt in range(MAX_RETRIES):
            result, raw = extract_page(
                model=model,
                page=page,
                page_num=page_num,
                cap=cap,
                law_name=law_name,
                **kwargs
            )

            if result is not None:
                return result, raw, MODELS[model_key]

            # Skip instantly on certain errors (no retries)
            if raw in ["EMPTY_RESPONSE", "SAFETY_BLOCKED", "NO_CANDIDATES", "TIMEOUT"]:
                print(f"  [Page {page_num + 1}] {raw} - skipping instantly")
                return None, raw, MODELS[model_key]

            # For other errors, try once more then move to next model
            if attempt < MAX_RETRIES - 1:
                print(f"  [Page {page_num + 1}] Retry {attempt + 1}/{MAX_RETRIES}...")
                time.sleep(RETRY_DELAY)
            else:
                print(f"  [Page {page_num + 1}] Failed with {MODELS[model_key]}, trying next model...")
                break

    # All models failed
    return None, "ALL_MODELS_FAILED", "none"


