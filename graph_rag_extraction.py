def process_law(
    pdf_path: str,
    cap: str,
    law_name: str,
    page_range: Optional[range] = None
) -> LawExtraction:
    """Process a complete law PDF and extract all content"""

    print(f"\n{'='*60}")
    print(f"Processing: {law_name} ({cap})")
    print(f"PDF: {pdf_path}")
    print(f"{'='*60}\n")

    # Determine law type
    is_subsidiary = is_subsidiary_legislation(cap)
    law_type = "subsidiary" if is_subsidiary else "chapter"
    content_key = get_content_type_name(cap)  # "articles" or "regulations"
    item_type = get_item_type(cap)  # "article" or "regulation"

    print(f"Law type: {law_type.upper()}")
    print(f"Content type: {content_key.upper()}")
    print()

    # Validate and Initialize Vertex AI
    if not PROJECT_ID:
        raise ValueError("GOOGLE_CLOUD_PROJECT not set in .env file")

    creds_path = os.environ.get('GOOGLE_APPLICATION_CREDENTIALS', '')
    if not creds_path or not Path(creds_path).exists():
        raise ValueError(f"Credentials file not found: {creds_path}")

    print(f"Project: {PROJECT_ID}")
    print(f"Location: {LOCATION}")
    print(f"Credentials: {Path(creds_path).name}")

    vertexai.init(project=PROJECT_ID, location=LOCATION)

    # Load models
    models = {}
    for key, model_name in MODELS.items():
        try:
            models[key] = GenerativeModel(model_name)
            print(f"Loaded model: {model_name}")
        except Exception as e:
            print(f"Warning: Could not load {model_name}: {e}")

    if not models:
        raise RuntimeError("No models available!")

    # Open PDF
    doc = fitz.open(pdf_path)
    total_pages = len(doc)

    # Determine pages to process
    if page_range is None:
        pages_to_process = range(total_pages)
    else:
        pages_to_process = page_range

    print(f"\nTotal pages in PDF: {total_pages}")
    print(f"Processing pages: {pages_to_process.start + 1} to {pages_to_process.stop}")
    print()

    # Track state
    all_items = {}  # Dict to merge items by main number
    all_schedules = {}  # Dict to merge schedules by ID
    all_miscellaneous = []  # Fallback extracted content
    all_edges = []
    skipped = []

    # Page-to-page state tracking
    prev_item_number = None
    prev_item_ended = True
    prev_schedule_section = None
    prev_schedule_ended = True
    prev_form_number = None
    prev_form_ended = True

    start_time = time.time()

    # Process each page
    for page_idx in pages_to_process:
        if page_idx >= total_pages:
            break

        page = doc[page_idx]
        print(f"[Page {page_idx + 1}/{total_pages}] Processing...", end=" ", flush=True)

        # Extract page
        result, raw, model_used = extract_with_fallback(
            models=models,
            page=page,
            page_num=page_idx,
            cap=cap,
            law_name=law_name,
            prev_item_number=prev_item_number,
            prev_item_ended=prev_item_ended,
            prev_schedule_section=prev_schedule_section,
            prev_schedule_ended=prev_schedule_ended,
            prev_form_number=prev_form_number,
            prev_form_ended=prev_form_ended
        )

        if result is None:
            # Try fallback extraction
            print(f"structured failed ({raw}), trying fallback...", end=" ", flush=True)
            fallback_result = None
            if "primary" in models:
                fallback_result = extract_fallback_text(
                    models["primary"],
                    page,
                    page_idx,
                    cap,
                    law_name
                )

            if fallback_result:
                all_miscellaneous.append(fallback_result)
                print(f"MISC (fallback OK)")
            else:
                print(f"SKIPPED (all failed)")
                skipped.append({
                    "page": page_idx + 1,
                    "reason": raw,
                    "model_attempted": model_used
                })
            continue

        # Handle skip pages
        page_content_type = result.get("page_content_type", "")
        if page_content_type == "skip":
            skip_reason = result.get("skip_reason", "unknown")
            print(f"SKIP ({skip_reason})")
            skipped.append({
                "page": page_idx + 1,
                "reason": skip_reason,
                "model_used": model_used
            })
            continue

        # Handle form pages (skip but track)
        if page_content_type in ["form", "form_template"]:
            form_num = result.get("last_form_number", "unknown")
            print(f"FORM ({form_num})")
            skipped.append({
                "page": page_idx + 1,
                "reason": f"form:{form_num}",
                "model_used": model_used
            })
            # Update form state
            prev_form_number = result.get("last_form_number")
            prev_form_ended = result.get("last_form_ended", True)
            continue

        # Process items (articles/regulations) - use dynamic key
        items = result.get(content_key, []) or result.get("articles", []) or result.get("regulations", [])
        items_found = 0

        for item in items:
            item_num = item.get("number", "")
            if not item_num:
                continue

            main_num = extract_main_number(item_num)
            item_id = generate_item_id(cap, main_num)

            # Check if this item continues from previous page
            if item.get("continues_from_previous") and main_num in all_items:
                # Append text to existing item
                existing = all_items[main_num]
                # Handle None text values
                existing_text = existing["text"] or ""
                new_text = item.get("text") or ""
                existing["text"] = existing_text + "\n" + new_text
                existing["page_end"] = page_idx + 1
                # Merge sub-items
                existing_subs = set(existing.get("sub_items", []))
                new_subs = set(item.get("sub_items", []))
                existing["sub_items"] = sorted(list(existing_subs | new_subs))
            else:
                # New item
                all_items[main_num] = {
                    "id": item_id,
                    "type": item_type,
                    "number": main_num,
                    "title": item.get("title") or "",
                    "text": item.get("text") or "",
                    "sub_items": item.get("sub_items", []),
                    "page_start": page_idx + 1,
                    "page_end": page_idx + 1,
                    "cross_references": {
                        "internal": [],
                        "external": []
                    }
                }
                items_found += 1

        # Process cross-references
        cross_refs = result.get("cross_references", [])
        for ref in cross_refs:
            # Get source item number (try multiple field names)
            source_num = ref.get(f"found_in_{item_type}", "") or ref.get("source_item", "") or ref.get("found_in_article", "") or ref.get("found_in_regulation", "")
            source_main = extract_main_number(source_num) if source_num else None

            if not source_main or source_main not in all_items:
                continue

            scope = ref.get("scope", "internal")
            target = ref.get("target", "")
            target_law = ref.get("target_law")

            if scope == "internal" and target:
                # Expand ranges like "311 to 318" into individual references
                expanded_targets = expand_reference_range(target)

                for single_target in expanded_targets:
                    target_main = extract_main_number(single_target)
                    target_id = generate_item_id(cap, target_main)

                    # Check if we have a sub-reference (e.g., "5(1)")
                    cleaned_target = clean_reference_target(single_target)
                    has_sub = cleaned_target != target_main

                    all_items[source_main]["cross_references"]["internal"].append({
                        "target": target_main,  # Clean number only
                        "target_id": target_id,
                        "sub_target": cleaned_target if has_sub else None
                    })

                    # Create edge for each expanded target
                    all_edges.append({
                        "source_id": all_items[source_main]["id"],
                        "target_id": target_id,
                        "type": "INTERNAL_REF",
                        "sub_target": cleaned_target if has_sub else None
                    })

            elif scope == "external" and target_law:
                # Use parse_external_reference for proper ID structure
                ext_ref = parse_external_reference(target, target_law)
                target_id = ext_ref["target_id"]

                if target_id:
                    all_items[source_main]["cross_references"]["external"].append({
                        "target": clean_reference_target(target) if target else None,
                        "target_law": target_law,
                        "target_id": target_id,
                        "has_article": ext_ref["has_article"]
                    })

                    # Create edge
                    all_edges.append({
                        "source_id": all_items[source_main]["id"],
                        "target_id": target_id,
                        "type": "EXTERNAL_REF",
                        "target_law": target_law
                    })

        # Process schedule content
        schedule_content = result.get("schedule_content", [])
        schedule_name = result.get("schedule_name") or "Schedule"  # Handle None explicitly
        schedules_found = 0

        if schedule_content or page_content_type in ["schedule_text", "schedule_table"]:
            sched_id = generate_schedule_id(cap, schedule_name)

            # Check if schedule already exists (continuation)
            if sched_id in all_schedules:
                existing_sched = all_schedules[sched_id]
                # Append content
                for section in schedule_content:
                    existing_sched["sections"].append(section)
                existing_sched["page_end"] = page_idx + 1
            else:
                # New schedule
                content_type = "fee_table" if page_content_type == "schedule_table" else "text"

                # Generate AI description for tables
                ai_description = None
                if content_type == "fee_table" and "primary" in models:
                    ai_description = generate_table_description(
                        models["primary"],
                        page,
                        law_name,
                        f"Schedule: {schedule_name}"
                    )

                all_schedules[sched_id] = {
                    "id": sched_id,
                    "type": "schedule",
                    "name": schedule_name,
                    "content_type": content_type,
                    "sections": schedule_content,
                    "ai_description": ai_description,
                    "page_start": page_idx + 1,
                    "page_end": page_idx + 1
                }
                schedules_found = 1

        # Process schedule regulations (REGULATION 1, 2, 3 inside schedules)
        schedule_regs = result.get("schedule_regulations", [])
        for sched_reg in schedule_regs:
            reg_num = sched_reg.get("regulation_number", "")
            sched_id = generate_schedule_id(cap, schedule_name, reg_num)

            if sched_id in all_schedules:
                # Continuation
                existing = all_schedules[sched_id]
                existing["text"] += "\n" + sched_reg.get("text", "")
                existing["page_end"] = page_idx + 1
            else:
                all_schedules[sched_id] = {
                    "id": sched_id,
                    "type": "schedule_regulation",
                    "schedule_name": schedule_name,
                    "regulation_number": reg_num,
                    "title": sched_reg.get("title", ""),
                    "text": sched_reg.get("text", ""),
                    "page_start": page_idx + 1,
                    "page_end": page_idx + 1
                }
                schedules_found += 1

        # Update state for next page (use dynamic field names)
        prev_item_number = result.get(f"last_{item_type}_on_page") or result.get("last_article_on_page") or result.get("last_regulation_on_page")
        prev_item_ended = result.get(f"last_{item_type}_ended", result.get("last_article_ended", result.get("last_regulation_ended", True)))
        prev_schedule_section = result.get("last_schedule_section")
        prev_schedule_ended = result.get("last_schedule_ended", True)
        prev_form_number = result.get("last_form_number")
        prev_form_ended = result.get("last_form_ended", True)

        # Print summary
        print(f"OK - {items_found} {content_key}, {schedules_found} schedules")

    doc.close()

    # Calculate metrics
    end_time = time.time()
    elapsed = end_time - start_time

    metrics = {
        "total_pages_in_pdf": total_pages,
        "pages_processed": len(pages_to_process),
        "pages_skipped": len(skipped),
        f"{content_key}_extracted": len(all_items),
        "schedules_extracted": len(all_schedules),
        "miscellaneous_extracted": len(all_miscellaneous),
        "edges_created": len(all_edges),
        "extraction_time_seconds": round(elapsed, 2),
        "extraction_timestamp": datetime.now().isoformat()
    }

    # Load/generate law metadata using cache (shared with multi_model_extraction)
    print("\nLoading law metadata...", end=" ", flush=True)
    metadata = None
    summaries_cache = load_summaries_cache()

    # Check if already cached
    if cap in summaries_cache:
        cached = summaries_cache[cap].get("summary", {})
        if cached.get("status") == "success":
            print(f"CACHED - Categories: {', '.join(cached.get('categories', []))}")
            metadata = LawMetadata(
                purpose=cached.get("purpose", ""),
                key_topics=cached.get("key_topics", []),
                scope=cached.get("scope", ""),
                categories=cached.get("categories", ["other"]),
                summary_text=cached.get("summary_text", ""),
                relation_to_parent=cached.get("relation_to_parent"),
                status="success"
            )

    # Not cached - generate new metadata
    if metadata is None and "primary" in models and all_items:
        print("generating...", end=" ", flush=True)

        # Get parent summary if this is subsidiary legislation
        parent_summary = None
        parent_code = get_parent_code(cap)
        if parent_code and parent_code in summaries_cache:
            parent_data = summaries_cache[parent_code].get("summary", {})
            if parent_data.get("status") == "success":
                parent_summary = parent_data.get("summary_text", "")
                print(f"(using parent {parent_code})...", end=" ", flush=True)

        metadata = generate_law_metadata(
            models["primary"],
            law_name,
            cap,
            list(all_items.values()),
            parent_summary
        )

        if metadata:
            print(f"OK - Categories: {', '.join(metadata.categories)}")
            # Cache this summary
            summaries_cache[cap] = {
                "code": cap,
                "name": law_name,
                "type": "subsidiary" if is_subsidiary else "parent",
                "parent_code": parent_code if is_subsidiary else None,
                "pdf_path": pdf_path,
                "summary": {
                    "purpose": metadata.purpose,
                    "key_topics": metadata.key_topics,
                    "scope": metadata.scope,
                    "categories": metadata.categories,
                    "relation_to_parent": metadata.relation_to_parent,
                    "summary_text": metadata.summary_text,
                    "status": "success"
                }
            }
            save_summaries_cache(summaries_cache)
            print(f"  Saved to cache: {SUMMARIES_CACHE_PATH}")
        else:
            print("FAILED (generation error)")
    elif metadata is None:
        print("SKIPPED (no items or models available)")

    # Build result
    return LawExtraction(
        law_code=cap,
        law_name=law_name,
        law_type=law_type,
        content_key=content_key,
        metadata=metadata,
        items=list(all_items.values()),
        schedules=list(all_schedules.values()),
        miscellaneous=all_miscellaneous,
        skipped=skipped,
        metrics=metrics,
        edges=all_edges
    )


def save_extraction(extraction: LawExtraction, output_dir: str = ".") -> str:
    """Save extraction result to JSON file"""

    # Build metadata dict if available (matches law_summaries.json structure)
    metadata_dict = None
    if extraction.metadata:
        metadata_dict = {
            "purpose": extraction.metadata.purpose,
            "key_topics": extraction.metadata.key_topics,
            "scope": extraction.metadata.scope,
            "categories": extraction.metadata.categories,
            "summary_text": extraction.metadata.summary_text,
            "relation_to_parent": extraction.metadata.relation_to_parent,
            "status": extraction.metadata.status
        }

    # Build output structure - metadata at the top for visibility
    output = {
        "law_code": extraction.law_code,
        "law_name": extraction.law_name,
        "law_type": extraction.law_type,
        "metadata": metadata_dict,
        extraction.content_key: extraction.items,
        "schedules": extraction.schedules,
        "miscellaneous": extraction.miscellaneous,
        "edges": extraction.edges,
        "skipped": extraction.skipped,
        "metrics": extraction.metrics
    }

    # Generate filename
    code_clean = normalize_code(extraction.law_code)
    filename = f"extraction_{code_clean}.json"
    filepath = os.path.join(output_dir, filename)

    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    print(f"\nSaved extraction to: {filepath}")
    return filepath


# =============================================================================
# INTERRUPT HANDLER
# =============================================================================

def handle_interrupt(signum, frame):
    """Handle Ctrl+C gracefully - save progress before exiting"""
    global _extraction_in_progress, _all_completed_extractions

    print("\n\n" + "="*60)
    print("INTERRUPT DETECTED - SAVING PROGRESS")
    print("="*60)

    # Save the current extraction if it was in progress
    if _extraction_in_progress is not None:
        print(f"\nSaving in-progress extraction: {_extraction_in_progress.law_code}")
        try:
            save_extraction(_extraction_in_progress, OUTPUT_DIR)
            print(f"[OK] Saved in-progress extraction")
        except Exception as e:
            print(f"[ERROR] Failed to save in-progress extraction: {e}")

    # Print summary of completed extractions
    print(f"\nCompleted extractions before interrupt: {len(_all_completed_extractions)}")
    for ext in _all_completed_extractions:
        items_count = ext.metrics.get(f"{ext.content_key}_extracted", 0)
        print(f"  - {ext.law_code}: {items_count} {ext.content_key}, {ext.metrics.get('edges_created', 0)} edges")

    print("\n[OK] Progress saved. You can resume extraction by running the script again.")
    print("Already extracted laws will be skipped if their JSON files exist.\n")
    sys.exit(0)


