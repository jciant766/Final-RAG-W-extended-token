def get_parent_code(sl_code: str) -> Optional[str]:
    """
    Extract parent Cap number from S.L. code.
    S.L. 9.01 -> Cap. 9
    S.L. 441.04 -> Cap. 441
    """
    if not sl_code or not sl_code.startswith("S.L."):
        return None
    parts = sl_code.replace("S.L.", "").strip().split(".")
    if parts:
        parent_num = parts[0].strip()
        return f"Cap. {parent_num}"
    return None


